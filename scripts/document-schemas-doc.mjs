#!/usr/bin/env node
/**
 * document-schemas-doc.mjs — write docs/Playbook-Document-Schemas.md, the
 * readable form of the machine schemas, so the page and the checkers cannot
 * disagree.
 *
 *   node scripts/document-schemas-doc.mjs          # rewrite the page
 *   node scripts/document-schemas-doc.mjs --check  # exit 1 if the page is stale
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const load = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const fmt = (b) => `${b[0].toLocaleString("en-US")} / ${b[1].toLocaleString("en-US")}`;

export function render() {
  const docs = load("playbook/document-schemas.json");
  const checklist = load("playbook/checklist-schema.json");
  const handoffs = load("playbook/handoff-schema.json");
  const out = [];
  out.push("# AI-First Playbook — Document Schemas", "");
  out.push("| | |", "|---|---|");
  out.push("| Purpose | For each document the Playbook produces: the sections it must have, in order; how big it may be; and what every row must contain. Checker scripts enforce this, so a document cannot drift from its shape. |");
  out.push("| Audience | Maintainers and approvers. Agents read the same rules in machine form (`playbook/*-schema*.json`). |");
  out.push("| Status | Generated by `scripts/document-schemas-doc.mjs` from the schema files; do not edit by hand. Built in reset Sessions 4 and 6 (2026-09-26). |");
  out.push("| Checkers | `checklist-lint.mjs`, `handoff-record.mjs validate`, `doc-check.mjs`, `template-lint.mjs` |", "");
  out.push("## 1. How a schema works", "");
  out.push("Each schema names the required sections in order, the optional ones, a word budget per size as TARGET / MAXIMUM, and the rule every row follows. The TARGET guides normal writing; the MAXIMUM fails the check. A scaffold script writes the skeleton; the checker prints one line per problem and exits non-zero.", "");
  out.push("## 2. Size", "");
  out.push("| Size | Active checklist items |", "|---|---:|");
  for (const [s, [lo, hi]] of Object.entries(checklist.checklist.sizes)) out.push(`| ${s} | ${lo}-${hi} |`);
  out.push(`| (split) | above ${checklist.checklist.split_above} |`, "");
  out.push("## 3. Implementation checklist", "");
  out.push(`Required sections in order: ${checklist.checklist.required_sections.join("; ")}. Optional: ${checklist.checklist.optional_sections.join("; ")}.`, "");
  out.push(`Item fields in order: ${checklist.item.field_order.join("; ")}. Required: ${checklist.item.required.join(", ")}; UI ref also for ${checklist.item.required_for_type["UI ref"].join(" and ")} items. Types: ${checklist.item.types.join(", ")}.`, "");
  out.push(`Item budget: ${fmt([checklist.item.budget_words.target, checklist.item.budget_words.max])} words at every size. Acceptance: "When <actor> <does what> on <screen>, then <observable result>", target ${checklist.item.acceptance.target_words}, maximum ${checklist.item.acceptance.max_words} words, one behaviour, no subjective words. Verify names an assertion and retained evidence. Metadata keys in order: ${checklist.metadata.keys.join(", ")}. Checker: \`checklist-lint.mjs\`.`, "");
  out.push("## 4. Handoff records", "");
  out.push(`Every kind carries the ten standing rows: ${Object.keys(handoffs.standing).join("; ")}. \`none\` is allowed only for ${handoffs.none_allowed.join(", ")}. Checker: \`handoff-record.mjs validate\`.`, "");
  out.push("| Kind | Rows in order | Small | Medium | Large |", "|---|---|---:|---:|---:|");
  for (const [kind, k] of Object.entries(handoffs.kinds)) out.push(`| ${kind} | ${k.fields.join("; ")} | ${fmt(k.budget.small)} | ${fmt(k.budget.medium)} | ${fmt(k.budget.large)} |`);
  out.push("");
  out.push("## 5. Human documents", "");
  out.push("Scaffold: `doc-scaffold.mjs <kind> <out> --feature=<name>`. Checker: `doc-check.mjs <doc> --size=<size>`.", "");
  let n = 1;
  for (const [kind, k] of Object.entries(docs.kinds)) {
    out.push(`### 5.${n++} ${k.title} — \`docs/<feature>/<Prefix>-<Feature>${k.file}\``, "");
    if (k.metadata.length) out.push(`Metadata rows: ${k.metadata.join("; ")}.`, "");
    out.push(`Sections in order: ${k.order.map((s) => (k.required.includes(s) ? s : `${s} (when ${k.conditional[s]})`)).join("; ")}.`, "");
    out.push("| Size | TARGET / MAXIMUM words |", "|---|---:|");
    for (const s of ["small", "medium", "large"]) out.push(`| ${s} | ${fmt(k.budget[s])} |`);
    out.push("", `Every row: ${k.rows}`, "");
  }
  out.push("## 6. Documents never rendered to HTML", "");
  out.push(`${docs.agent_documents.map((d) => `\`*${d}\``).join(", ")}, and any checklist. \`render-docs.mjs\` skips them.`, "");
  return out.join("\n");
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const path = join(root, "docs/Playbook-Document-Schemas.md");
  const text = render();
  if (process.argv.includes("--check")) {
    const same = readFileSync(path, "utf8") === text;
    console.log(same ? "document schemas page is current" : "docs/Playbook-Document-Schemas.md is stale; run node scripts/document-schemas-doc.mjs");
    process.exit(same ? 0 : 1);
  }
  writeFileSync(path, text);
  console.log("wrote docs/Playbook-Document-Schemas.md");
}
